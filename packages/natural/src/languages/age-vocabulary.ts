export function ageTokens(input: string, language: Language, lexicon: Lexicon): string {
  if (language === 'en') return input;
  const vocabulary = { ...ageVocabulary[language] };
  for (const name of [
    'january',
    'february',
    'march',
    'april',
    'may',
    'june',
    'july',
    'august',
    'september',
    'october',
    'november',
    'december',
  ]) {
    const aliases = lexicon[name];
    for (const alias of typeof aliases === 'string' ? [aliases] : (aliases ?? []))
      vocabulary[alias] = name;
  }
  const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = new RegExp(
    '(?<![a-zà-ÿ])(?:' +
      Object.keys(vocabulary)
        .sort((a, b) => b.length - a.length)
        .map(escape)
        .join('|') +
      ')(?![a-zà-ÿ])',
    'g'
  );
  return input
    .replace(pattern, (term) => vocabulary[term]!)
    .replace(/\s+/g, ' ')
    .trim();
}
